import { test, expect } from '@playwright/test';
test('recibir, cobrar, procesar y entregar desde el navegador', async ({ page }) => {
  const errors: string[] = []; page.on('pageerror', e => errors.push(e.message));
  await page.goto('/');
  await page.getByRole('button', { name: 'Crear lavandería' }).click();
  await page.getByLabel('Tu nombre').fill('Operador de prueba');
  await page.getByLabel('Nombre de la lavandería').fill('Lavandería E2E');
  await page.getByLabel('Correo electrónico').fill(`browser-${crypto.randomUUID()}@example.test`);
  await page.getByLabel('Contraseña', { exact: true }).fill('Prueba-segura-123!');
  await page.getByRole('button', { name: 'Crear mi cuenta' }).click();
  await expect(page.getByRole('heading', { name: 'Buen día. Todo bajo control.' })).toBeVisible();
  await page.screenshot({ path: 'test-results/dashboard-desktop.png', fullPage: true });
  await page.getByRole('button', { name: 'Clientes', exact: true }).click();
  await page.getByRole('button', { name: 'Nuevo cliente' }).click();
  await page.getByLabel('Nombre completo').fill('María de prueba');
  await page.getByLabel('Celular').fill('51912345678');
  await page.getByRole('button', { name: 'Guardar', exact: true }).click();
  await expect(page.getByRole('cell', { name: 'María de prueba', exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Órdenes', exact: true }).click();
  await page.getByRole('button', { name: 'Recibir pedido' }).click();
  await page.getByLabel('Cliente', { exact: true }).selectOption({ label: 'María de prueba · 51912345678' });
  await page.getByLabel('Servicio', { exact: true }).selectOption({ label: 'Lavado de ropa · S/ 6.00/kg' });
  await page.getByLabel('Kg / piezas reales').fill('2');
  await page.getByRole('button', { name: 'Crear orden', exact: true }).click();
  const order = page.getByRole('dialog', { name: 'Orden #0001' });
  await expect(order).toBeVisible();
  await expect(order.locator('.totals')).toContainText('18.00');
  await page.getByRole('button', { name: 'Registrar pago', exact: true }).click();
  const payment = page.getByRole('dialog', { name: 'Registrar pago' });
  await payment.getByLabel('Medio de pago').selectOption('yape');
  await payment.getByRole('button', { name: 'Registrar pago', exact: true }).click();
  await expect(payment).not.toBeVisible();
  await page.getByRole('button', { name: 'Iniciar lavado' }).click();
  await page.getByRole('button', { name: 'Marcar listo' }).click();
  await page.getByRole('button', { name: 'Entregar pedido' }).click();
  await expect(order.locator('.badge')).toHaveText('Entregado');
  await page.emulateMedia({ media: 'print' });
  await expect(order.locator('.ticket')).toBeVisible();
  await expect(page.locator('.sidebar')).not.toBeVisible();
  await page.emulateMedia({ media: 'screen' });
  await order.getByRole('button', { name: 'Cerrar', exact: true }).click();
  await page.setViewportSize({ width: 360, height: 800 });
  await expect(page.getByRole('button', { name: 'Abrir menú' })).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.getByRole('button', { name: 'Abrir menú' }).click();
  await page.getByRole('button', { name: 'Resumen', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Buen día. Todo bajo control.' })).toBeVisible();
  await page.screenshot({ path: 'test-results/dashboard-mobile.png', fullPage: true, animations: 'disabled' });
  await page.setViewportSize({ width: 768, height: 1024 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  expect(errors).toEqual([]);
});
