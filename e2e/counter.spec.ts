test('caché de catálogo, cambio de cuenta y sesión revocada', async ({ page }) => {
  async function register(name: string) {
    await page.getByRole('button', { name: 'Crear lavandería' }).click();
    await page.getByLabel('Tu nombre').fill(name);
    await page.getByLabel('Nombre de la lavandería').fill(name);
    await page.getByLabel('Correo electrónico').fill(`${crypto.randomUUID()}@example.test`);
    await page.getByLabel('Contraseña', { exact: true }).fill('Cuenta-prueba-123!');
    await page.getByRole('button', { name: 'Crear mi cuenta' }).click();
    await expect(page.getByRole('heading', { name: 'Buen día. Todo bajo control.' })).toBeVisible();
  }
  await page.goto('/');
  await register('Primera cuenta caché');
  await page.getByRole('button', { name: 'Clientes', exact: true }).click();
  await page.getByRole('button', { name: 'Nuevo cliente' }).click();
  await page.getByLabel('Nombre completo').fill('Cliente privado primera empresa');
  await page.getByRole('button', { name: 'Guardar', exact: true }).click();
  await expect(page.getByRole('cell', { name: 'Cliente privado primera empresa', exact: true })).toBeVisible();

  let catalogRequests = 0;
  page.on('request', request => {
    if (new URL(request.url()).pathname === '/api/services' && request.method() === 'GET') catalogRequests++;
  });
  await page.getByRole('button', { name: 'Servicios', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Edredón', exact: true })).toBeVisible();
  const initial = catalogRequests;
  await page.getByRole('button', { name: 'Resumen', exact: true }).click();
  await page.getByRole('button', { name: 'Servicios', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Edredón', exact: true })).toBeVisible();
  expect(catalogRequests).toBe(initial);

  await page.getByRole('button', { name: 'Cerrar sesión' }).click();
  await expect(page.getByRole('button', { name: 'Ingresar', exact: true })).toBeVisible();
  await register('Segunda cuenta caché');
  await page.getByRole('button', { name: 'Clientes', exact: true }).click();
  await expect(page.getByText('Agrega tu primer cliente para recibir un pedido.')).toBeVisible();
  await expect(page.getByRole('cell', { name: 'Cliente privado primera empresa', exact: true })).toHaveCount(0);

  const logout = await page.request.post('/api/auth/logout', { headers: { Origin: 'http://localhost:5174' } });
  expect(logout.ok()).toBe(true);
  await page.getByRole('button', { name: 'Órdenes', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Ingresar', exact: true })).toBeVisible();
});
